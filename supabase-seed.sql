create extension if not exists pgcrypto;

create table if not exists public.profile (
  id uuid primary key default gen_random_uuid(),
  name_ko text,
  name_en text,
  facts jsonb,
  debut_date date,
  notes jsonb
);

create table if not exists public.works (
  id uuid primary key default gen_random_uuid(),
  year int,
  title text,
  role text,
  venue text,
  run text,
  kind text
);

create table if not exists public.schedule (
  id uuid primary key default gen_random_uuid(),
  date date,
  time text,
  title text,
  role text,
  venue text,
  note text
);

create table if not exists public.gallery (
  id text primary key,
  caption text,
  ratio text,
  tag text
);

create table if not exists public.concerts (
  id uuid primary key default gen_random_uuid(),
  date text,
  title text,
  "with" text
);

truncate table public.profile cascade;
truncate table public.works cascade;
truncate table public.schedule cascade;
truncate table public.gallery cascade;
truncate table public.concerts cascade;

